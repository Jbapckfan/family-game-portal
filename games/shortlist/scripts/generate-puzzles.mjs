const WORDS = [...new Set(vocabulary)].sort();
for (const word of WORDS) if (!/^[A-Z]{5}$/.test(word)) throw new Error(`Invalid authored word: ${word}`);
let seed = 20261020;
function random() {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 4294967296;
}
function shuffled(items) {
  const copy = [...items];
  for (let index = copy.length - 1; index > 0; index--) {
    const other = Math.floor(random() * (index + 1));
    [copy[index], copy[other]] = [copy[other], copy[index]];
  }
  return copy;
}
const signature = word => [...new Set(word)].sort().join('');
const opening = 'CRANE BRICK GHOST PLUMB FJORD WATCH SILKY DROWN MAPLE SCOUT FLING QUEST'.split(' ');
const usage = new Map(WORDS.map(word => [word, 0]));
const puzzles = [];
const sets = new Set();
const answers = ['MAPLE', ...shuffled(WORDS.filter(word => word !== 'MAPLE')).slice(0, 89)];

for (let index = 0; index < 180; index++) {
  // Consume the original random stream unchanged until all 90 published boards
  // have been reconstructed. Adding answers earlier would rewrite their boards.
  if (index === 90) answers.push(...shuffled(WORDS.filter(word => !answers.includes(word))).slice(0, 90));
  const answer = answers[index];
  let words;
  let tree;
  for (let attempt = 0; attempt < 1000; attempt++) {
    if (index === 0) words = [...opening];
    else {
      const ranked = shuffled(WORDS).sort((a, b) => usage.get(a) - usage.get(b));
      words = [answer];
      const signatures = new Set([signature(answer)]);
      for (const word of ranked) {
        if (signatures.has(signature(word))) continue;
        words.push(word);
        signatures.add(signature(word));
        if (words.length === 12) break;
      }
      words = shuffled(words);
      // Cycling the answer's position avoids a fixed-location shortcut or clumpy random positions.
      const targetPosition = (index * 5 + 8) % 12;
      const currentPosition = words.indexOf(answer);
      [words[targetPosition], words[currentPosition]] = [words[currentPosition], words[targetPosition]];
    }
    const key = [...words].sort().join(',');
    if (sets.has(key)) continue;
    tree = solveDecisionTree(words, 3);
    if (!tree) continue;
    sets.add(key);
    break;
  }
  if (!tree) throw new Error(`Could not certify board ${index + 1}`);
  for (const word of words) usage.set(word, usage.get(word) + 1);
  puzzles.push({
    id: `shortlist-${String(index + 1).padStart(3, '0')}`,
    title: 'Small signals. Big deductions.',
    difficulty: tree.expectedScans >= 2.75 ? 'Tricky' : 'Sharp',
    words, answer,
  });
}

const usedWords = new Set(puzzles.flatMap(puzzle => puzzle.words));
const collection = {
  boards: puzzles.length, words: usedWords.size, maxScans: 3,
  checkedAnswerPaths: puzzles.length * 12,
  source: 'Authored vocabulary; deterministic exact decision-tree validation.',
  cycle: 'The 180-board collection repeats after 180 days.',
};
const output = `// Generated by scripts/generate-puzzles.mjs. Do not edit by hand.\nexport const COLLECTION = ${JSON.stringify(collection, null, 2)};\n\nexport const PUZZLES = ${JSON.stringify(puzzles, null, 2)};\n`;
const path = fileURLToPath(new URL('../puzzles.mjs', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Generated collection differs from the checked-in file.');
} else writeFileSync(path, output);
console.log(JSON.stringify({ ...collection, maxWordUses: Math.max(...usage.values()), unusedAuthoredWords: WORDS.length - usedWords.size }));
