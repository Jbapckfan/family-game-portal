/** Reproducible, offline authoring of Territory's separate exact-capture edition. */
import {writeFile} from 'node:fs/promises';
import * as E from '../games/qwen-territory-tactics/engine.mjs';
const base={radius:3,maxMoves:3,captureRule:'exact'},all=E.cells(base),adj=new Map(all.map(c=>[c,E.neighbors(base,c)]));
let seed=0x06112026;
const random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/4294967296;};
const pick=a=>a[Math.floor(random()*a.length)];
const shuffled=a=>{a=[...a];for(let i=a.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[a[i],a[j]]=[a[j],a[i]];}return a;};
export function symmetryKey(p,enemyOnly=false){
 const variants=[];
 for(let reflection=0;reflection<2;reflection++)for(let rotation=0;rotation<6;rotation++){
  const transform=cell=>{let [q,r]=cell.split(',').map(Number);if(reflection)[q,r]=[r,q];for(let n=0;n<rotation;n++)[q,r]=[-r,q+r];return `${q},${r}`;};
  variants.push(JSON.stringify([p.radius,enemyOnly?[]:p.friendly.map(transform).sort(),p.enemy.map(transform).sort(),enemyOnly?null:p.target,p.maxMoves]));
 }
 return variants.sort()[0];
}
function candidate(combination){
 const target=combination?pick([3,4,5]):pick([3,4,5,6]);
 const small=combination?pick(Array.from({length:target-1},(_,i)=>i+1)):pick([1,2]);
 const sizes=combination?[small,target-small,target+pick([1,2])]:[target,small,target+pick([1,2])];
 let enemy=[],groups=[];
 for(const size of sizes){
  const allowed=all.filter(c=>!enemy.includes(c)&&!adj.get(c).some(n=>enemy.includes(n)));
  if(!allowed.length)return;
  const group=[pick(allowed)];
  for(let i=1;i<size;i++){const frontier=[...new Set(group.flatMap(c=>adj.get(c)).filter(c=>allowed.includes(c)&&!group.includes(c)))];if(!frontier.length)return;group.push(pick(frontier));}
  groups.push(group);enemy.push(...group);
 }
 const boundary=[...new Set(enemy.flatMap(c=>adj.get(c)).filter(c=>!enemy.includes(c)))];
 let holes=[];
 for(let i=0;i<groups.length;i++){
  const touching=boundary.filter(c=>adj.get(c).some(n=>groups[i].includes(n)));
  const count=combination?(i<2?2:pick([2,3])):(i===0?3:pick([1,2,3]));
  if(touching.length<count)return;
  holes.push(...shuffled(touching).slice(0,count));
 }
 holes=[...new Set(holes)];
 const p={...base,friendly:boundary.filter(c=>!holes.includes(c)).sort(),enemy:enemy.sort(),target};
 if(all.length-p.enemy.length-p.friendly.length<8)return;
 const liberties=groups.map(g=>E.liberties(p,g,p.friendly,p.enemy));
 if(liberties.some(l=>l.length<1||l.length>3))return;
 if(combination?new Set([...liberties[0],...liberties[1]]).size!==3:liberties[0].length!==3)return;
 if(E.groups(p,p.friendly).some(g=>!E.liberties(p,g,p.friendly,p.enemy).length))return;
 const wins=E.winningPaths(p);
 if(!wins.length||wins.some(path=>path.length!==3))return;
 // Traps must be actual legal captures, not just visual distractors.
 const below=E.winningPaths({...p,target:sizes[1]}).find(path=>{const c=E.simulate(p,path).captured;return c>0&&c<target;});
 const above=E.winningPaths({...p,target:sizes[2]}).find(path=>E.simulate(p,path).captured>target);
 if(!below||!above)return;
 // At least six playable first choices, and some attractive captures are wrong.
 if(all.filter(c=>E.applyMove(p,{friendly:p.friendly,enemy:p.enemy,captured:0},c)).length<6)return;
 return {p,combination,solution:wins[0],below,above};
}
if(process.argv[1]&&new URL(import.meta.url).pathname===process.argv[1]){
 const bank=[],proof=[],seen=new Set(),enemySeen=new Set();let attempts=0;
 while(bank.length<240&&attempts++<500000){
  const item=candidate(bank.length%2===1);if(!item)continue;
  const key=symmetryKey(item.p),enemyKey=symmetryKey(item.p,true);if(seen.has(key)||enemySeen.has(enemyKey))continue;
  const p={id:`territory-exact-${String(bank.length+1).padStart(3,'0')}`,...item.p};
  bank.push(p);proof.push({id:p.id,kind:item.combination?'combine-groups':'select-group',solution:item.solution,under:item.below,over:item.above});seen.add(key);enemySeen.add(enemyKey);
 }
 if(bank.length!==240)throw Error(`Only ${bank.length} accepted after ${attempts} attempts`);
 await writeFile(new URL('../games/qwen-territory-tactics/exact-puzzles.mjs',import.meta.url),`// Separate exact edition. Do not rename IDs or alter published records.\n// Generated by scripts/MAKER-codex__build-territory-exact.mjs; legacy puzzles.mjs stays intact.\nexport const EXACT_PUZZLES = ${JSON.stringify(bank,null,2)};\nexport const EXACT_EDITION = 'exact-v2';\n`);
 await writeFile(new URL('../output/MAKER-codex__territory-exact-20261106/content-proof.json',import.meta.url),JSON.stringify({seed:'0x06112026',attempts,count:bank.length,proof},null,2));
 console.log(JSON.stringify({attempts,count:bank.length,combination:proof.filter(p=>p.kind==='combine-groups').length,targets:[...new Set(bank.map(p=>p.target))].sort()},null,2));
}
