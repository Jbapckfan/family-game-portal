#!/usr/bin/env node
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {calendarDates,loadDailyAudit} from './daily-audit-lib.mjs';

const baseline = JSON.parse(await readFile(new URL('../docs/six-month-previous-calendar.json',import.meta.url),'utf8'));
const editorialHolds=JSON.parse(await readFile(new URL('../docs/daily-editorial-holds.json',import.meta.url),'utf8'));
const {games,cleanup} = await loadDailyAudit();
try {
  const rotations = {}, originalCounts = {};
  for (const game of games.filter(game=>game.creator !== 'Kimi')) {
    const previous = baseline.games.find(old=>old.slug === game.slug);
    assert.ok(previous);
    assert.equal(game.puzzles[previous.todayIndex].id,previous.todayId);
    const held=new Set(Object.keys(editorialHolds.games[game.slug]??{}));
    assert.ok(!held.has(previous.todayId),`${game.slug}: today's published board cannot be silently replaced`);
    for(const id of held)assert.ok(game.puzzles.some(puzzle=>puzzle.id===id),`${game.slug}: unknown editorial hold ${id}`);
    const recentlyScheduled=new Set(calendarDates('2026-10-20','2026-10-29').map(date=>game.key(game.select(date).puzzle)));
    const seen = new Set([game.key(game.puzzles[previous.todayIndex])]), indices = [], deferred = [];
    for (let offset=1;offset<game.puzzles.length;offset++) {
      const index=(previous.todayIndex+offset)%game.puzzles.length, key=game.key(game.puzzles[index]);
      if(held.has(game.puzzles[index].id))continue;
      if (seen.has(key)) continue;
      seen.add(key);
      (recentlyScheduled.has(key)?deferred:indices).push(index);
    }
    assert.ok(indices.length>=181,`${game.slug}: insufficient unseen challenges after the opening week`);
    indices.push(...deferred);
    indices.push(previous.todayIndex);
    assert.ok(indices.length >= 200,`${game.slug}: insufficient substantive reserve`);
    rotations[game.slug]={from:'2026-10-30',bankCount:game.puzzles.length,indices};
    if (game.creator === 'Alford Daily') originalCounts[game.slug]=previous.count;
  }
  // Retain the original protected prefix and cover the next 182 dates from Nov 1.
  const dates=calendarDates('2026-10-29','2027-05-02');
  const reservations={start:dates[0],end:dates.at(-1),byGame:{}};
  for(const game of games){
    const release=rotations[game.slug];
    reservations.byGame[game.slug]={bankCount:game.puzzles.length,indices:dates.map(date=>{
      if(!release)return game.select(date).index;
      if(date<release.from)return baseline.games.find(old=>old.slug===game.slug).todayIndex;
      const elapsed=(Date.parse(date)-Date.parse(release.from))/86400000;
      return release.indices[elapsed%release.indices.length];
    })};
  }
  const source = `/** Generated by scripts/build-six-month-calendar.mjs. Preserve published dates. */
export const ORIGINAL_BANK_COUNTS = Object.freeze(${JSON.stringify(originalCounts,null,2)});
export const FRESH_ROTATIONS = Object.freeze(Object.fromEntries(Object.entries(${JSON.stringify(rotations,null,2)}).map(([slug,release])=>[slug,Object.freeze({...release,indices:Object.freeze(release.indices)})])));
export const DAILY_RESERVATIONS = Object.freeze(${JSON.stringify(reservations,null,2)});

/** Null leaves older releases and reduced fixture banks on their existing selector. */
export function releasedDailyIndex(slug,key,count) {
  const release=FRESH_ROTATIONS[slug];
  if(!release || key<release.from || count<release.bankCount)return null;
  const elapsed=(Date.parse(key+'T00:00:00Z')-Date.parse(release.from+'T00:00:00Z'))/86400000;
  if(!Number.isSafeInteger(elapsed) || elapsed<0)return null;
  return release.indices[elapsed%release.indices.length];
}

export function originalDailyIndex(slug,key,ordinal,count) {
  const released=releasedDailyIndex(slug,key,count);
  if(released!==null)return released;
  const historicalCount=Math.min(count,ORIGINAL_BANK_COUNTS[slug]??count);
  return ((ordinal%historicalCount)+historicalCount)%historicalCount;
}
`;
  const target=new URL('../games/deepseek-runtime/daily-rotations.mjs',import.meta.url);
  if(process.argv.includes('--write'))await writeFile(target,source);
  else assert.equal(await readFile(target,'utf8'),source,'Regenerate the dated calendar');
  console.log(`Verified ${Object.keys(rotations).length} dated rotations with at least 200 substantive challenges each.`);
} finally { await cleanup(); }
