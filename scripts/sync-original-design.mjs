import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const identities = JSON.parse(await readFile(path.join(root, 'design/identities.json'), 'utf8'));
const base = await readFile(path.join(root, 'design/collection-base.css'), 'utf8');
const boundary = '/* ALFORD COLLECTION DESIGN — generated by scripts/sync-original-design.mjs */';
const originals = ['ringcount','switchpath','counterpart','shortlist','second-sense','sideways','tradeoff','inbetween'];
for (const slug of originals) {
  const file = path.join(root, 'games', slug, 'styles.css');
  const old = (await readFile(file, 'utf8')).split(boundary)[0].trimEnd();
  const skin = await readFile(path.join(root, 'design/boards', `${slug}.css`), 'utf8');
  const id = identities[slug];
  const palette = `body.${slug}{--accent:${id.accent};--accent-dark:${id.dark};--wash:${id.wash};--soft:${id.edge};--ink:#202c35;--muted:#5b666c;--paper:#f6f3ec;--white:#fffefa;--line:#dcded8}`;
  await writeFile(file, `${old}\n\n${boundary}\n${base}\n${palette}\n${skin}\n`);
}
console.log(`Applied shared chrome and eight distinct board identities.`);
