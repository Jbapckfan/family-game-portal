async function fresh(request) {
  // Always ask the server: an unchanged file costs a 304, a changed one is downloaded.
  const response = await fetch(request, { cache: 'no-cache' });
  await save(request, response);
  return response;
}

async function networkFirst(request, isPage) {
  try { return await fresh(request); }
  catch { return await saved(request, isPage) || offline(request, isPage); }
}

async function cacheFirst(request) {
  const cached = await saved(request, false);
  if (cached) return cached;
  try { return await fresh(request); }
  catch { return Response.error(); }
}

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (bypass(request, url)) return;
  const path = relativePath(url);
  const isPage = request.mode === 'navigate' || request.destination === 'document';
  if (path.startsWith('games/vendor/') || path.startsWith('games/fonts/') || /\.(woff2?|ttf|otf)$/i.test(path)) {
    event.respondWith(cacheFirst(request));
  } else if (request.destination === 'image' || /\.(avif|webp|png|jpe?g|gif|svg|ico)$/i.test(path)) {
    const refresh = fresh(request).catch(() => undefined);
    event.waitUntil(refresh.then(() => undefined));
    event.respondWith((async () => await saved(request, false) || await refresh || Response.error())());
  } else {
    event.respondWith(networkFirst(request, isPage));
  }
});

async function precacheFile(cache, path) {
  const url = new URL(path, SCOPE).href;
  const response = await fetch(url, { cache: 'no-cache' });
  if (!response.ok) throw new Error(`Could not save ${path}`);
  await cache.put(url, response);
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await Promise.all(CORE_FILES.map(path => precacheFile(cache, path)));
    const optional = PRECACHE_FILES.filter(path => !CORE_FILES.includes(path));
    // Bound parallel downloads; an optional 404 must not discard the working shell.
    let next = 0;
    await Promise.all(Array.from({ length: Math.min(6, optional.length) }, async () => {
      while (next < optional.length) {
        const path = optional[next++];
        try { await precacheFile(cache, path); } catch { /* Retry on a later online visit. */ }
      }
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
      .map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});
